const MAX_PICK = 3;   // 다 고르면 결국 아무거나가 된다

function byId(id) {
  return FORMS.find((f) => f.id === String(id || '').trim()) || null;
}

/** 고른 것 중 쓸 수 있는 것만 남긴다 */
function clean(ids, opts) {
  const o = opts || {};
  const seen = new Set();
  const out = [];
  (Array.isArray(ids) ? ids : []).forEach((id) => {
    const f = byId(id);
    if (!f || seen.has(f.id)) return;
    /* 인사글 재료가 없으면 인사형은 못 만든다. 지어내게 두느니 뺀다. */
    if (f.needsIntro && !o.hasIntro) return;
    seen.add(f.id);
    out.push(f.id);
  });
  return out.slice(0, MAX_PICK);
}

/** 이번 차례에 쓸 틀 하나. 고른 것들을 돌려 쓴다. */
function next(ids, cursor) {
  const list = Array.isArray(ids) && ids.length ? ids : ['info'];
  return byId(list[Math.abs(Number(cursor) || 0) % list.length]) || byId('info');
}

/** 프롬프트에 덧붙일 덩어리 */
function block(form) {
  if (!form) return '';
  return '════════ 이번 글의 모양 ════════\n' + form.block + '\n';
}

module.exports = { FORMS, MAX_PICK, byId, clean, next, block };
