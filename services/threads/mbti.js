const NAMES = Object.keys(TYPES);

/** MBTI 이야기인가. 주제나 글에 「MBTI」나 유형 이름이 있으면 그렇다. */
function isMbti(text) {
  const t = String(text || '').toUpperCase();
  if (t.indexOf('MBTI') >= 0) return true;
  return NAMES.some((n) => t.indexOf(n) >= 0);
}

