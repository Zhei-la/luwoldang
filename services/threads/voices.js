function byId(id) {
  return PRESETS.find((p) => p.id === String(id || '').trim()) || null;
}

/** 프리셋을 프롬프트에 넣을 모양으로 편다 */
function presetBlock(preset) {
  return [
    '고른 말투: ' + preset.label,
    '',
    ...preset.rules.map((r) => '- ' + r),
  ].join('\n');
}

module.exports = { PRESETS, byId, presetBlock };
