const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

/**
 * 글 한 줄을 화면에 뿌릴 HTML 로 바꾼다.
 * 글자는 먼저 전부 escape 하므로, 글 안에 꺾쇠가 섞여 들어와도
 * 태그로 실행되지 않고 글자로만 보인다. 그 뒤에 우리 표기만 되살린다.
 *
 * @param {string} line  글 한 줄 (종류 글자는 뗀 상태)
 * @param {string} base  이 손님이 들어온 주소의 앞자리. '' 이거나 '/saju@아무개'
 */
function format(line, base) {
  let out = esc(line);
  out = out.replace(/\[\[([a-z0-9-]+)\|([^\]|]+)\]\]/g,
    (_, slug, text) => '<a href="' + esc(base || '') + '/guide/' + slug + '">' + text + '</a>');
  out = out.replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
  return out;
}

