/* 검색 — 초성이나 한 글자만 쳐도 걸리게 한다.
 * 통화 중에 정확히 칠 시간이 없다. */
function norm(s) {
  return String(s || '').toLowerCase().replace(/\s+/g, '');
}

function search(q) {
  const k = norm(q);
  if (!k) return [];
  const hit = [];
  for (const it of TERMS) {
    const names = [it.t].concat(it.alt || []);
    let score = -1;
    for (const n of names) {
      const nn = norm(n);
      if (nn === k) { score = 100; break; }
      if (nn.indexOf(k) === 0) { score = Math.max(score, 80); }
      else if (nn.indexOf(k) > -1) { score = Math.max(score, 60); }
    }
    if (score < 0 && norm(it.short).indexOf(k) > -1) score = 30;
    if (score >= 0) hit.push({ it, score });
  }
  hit.sort((a, b) => b.score - a.score || a.it.t.length - b.it.t.length);
  return hit.map((h) => h.it);
}

