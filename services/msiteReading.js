function moreTenGod(c, w) {
  const out = [];
  const detail = c.십성상세 || {};
  const top = Object.keys(detail).sort((a, b) => detail[b] - detail[a]).filter((k) => TG[k]);
  top.slice(0, 3).forEach((k) => {
    out.push(은('<b>' + k + '</b>') + ' ' + detail[k] + '개. ' + TG[k] + '.');
  });

  const d = c.십성분포 || {};
  const none = Object.keys(GROUP).filter((k) => !(d[k] > 0));
  if (none.length) {
    out.push('반대로 ' + 이(none.map((k) => '<b>' + k + '</b>').join('과 ')) + ' 한 글자도 없습니다. ' +
      none.map((k) => GROUP[k].good.split(',')[0]).join(', ') +
      ' 쪽은 타고난 힘으로 굴러가지 않습니다. 이런 자리는 사람이나 환경으로 메우는 것이 답이고, ' +
      '어떤 사람을 곁에 둬야 하는지가 그래서 중요해집니다.');
  }

  if (!none.length) {
    const thin = Object.keys(GROUP).sort((x, y) => (d[x] || 0) - (d[y] || 0))[0];
    if (thin) {
      out.push('가장 얇은 쪽은 ' + 이('<b>' + thin + '</b>') + '입니다. ' +
        GROUP[thin].good.split(',')[0] + ' 쪽이 아주 없지는 않지만 힘이 약해서, ' +
        '중요한 순간마다 여기서 걸립니다. 이 자리를 채워주는 사람이 곁에 있으면 판이 크게 달라집니다.');
    }
  }

  const mine = [];
  (w || []).forEach((p) => (p.sinsal || []).forEach((x) => {
    if (SINSAL[x] && mine.indexOf(x) === -1) mine.push(x);
  }));
  if (mine.length) {
    out.push('가지고 계신 신살 중 눈에 띄는 것은 ' +
      mine.slice(0, 3).map((x) => '<b>' + esc(x) + '</b>').join(', ') + '입니다. ' +
      mine.slice(0, 3).map((x) => 은(x) + ' ' + SINSAL[x]).join('. ') + '.');
  }
  return out;
}

function moreYear(c) {
  const out = [];
  const cur = c.현재대운, nx = c.다음대운, se = c.올해세운, wo = c.이번달월운;
  if (cur && cur.간지) {
    out.push('지금은 <b>' + esc(cur.간지) + ' 대운</b> 한가운데입니다. ' +
      (cur.나이 != null ? cur.나이 + '세에 들어온 십 년이고, ' : '') +
      이(esc(String(cur.십성 || '').split('/')[0])) + ' 앞에 서는 시기입니다.' +
      (UNSEONG[cur.운성] ? ' ' + UNSEONG[cur.운성] + '.' : ''));
  }
  if (nx && nx.나이 != null) {
    const a = nx.나이;
    out.push('<b>' + a + '세</b>에 판이 한 번 바뀝니다. 실제로는 ' + (a - 2) + '세 무렵부터 조짐이 오고 ' +
      (a + 1) + '세까지 두 기운이 겹칩니다. ' +
      '이 시기에 자리를 옮기거나 관계가 정리되는 분이 많습니다.');
  }
  if (se && se.간지) {
    /* ⚠️ 대운 운성 설명을 여기서 또 쓰면 안 된다. 우연히 같은 자리면
       바로 위 문단과 토씨까지 같은 글이 두 번 나온다 — 채우기로 읽힌다. */
    const sg = esc(String(se.십성 || '').split('/')[0]);
    out.push('올해 ' + (se.년도 || '') + '년은 ' + 이('<b>' + sg + '</b>') + ' 강하게 들어옵니다. ' +
      '십 년의 큰 흐름 위에 올해만의 결이 따로 얹히기 때문에, ' +
      '대운이 순해도 올해가 버거울 수 있고 그 반대일 수도 있습니다.');
  }
  if (wo && wo.간지) {
    out.push('이번 달은 ' + esc(String(wo.십성 || '').split('/')[0]) + '의 달입니다. ' +
      '한 해의 흐름 위에 달마다 결이 한 겹씩 더 얹히기 때문에, ' +
      '같은 해에도 되는 달과 안 되는 달이 뚜렷하게 갈립니다.');
  }
  out.push('<b>어느 달에 밀고 어느 달에 멈춰야 하는지</b>, 지금 대운이 당신에게 순한 십 년인지 ' +
    '버텨야 하는 십 년인지, 어떤 일과 어떤 사람이 맞는지는 ' +
    '여덟 글자를 직접 읽어야 나옵니다. 사주를 신청하시면 여기서부터 이어 풀어 드립니다.');
  return out;
}

/**
 * 「여기서부터는 사람이 읽습니다」 밑에 보이는 맛보기.
 * 예전에는 누구에게나 똑같은 글이 나갔다. 그 사람 사주에서 뽑아 쓴다.
 */
function teaserOf(c) {
  const cur = c.현재대운 || {}, nx = c.다음대운 || {}, se = c.올해세운 || {};
  const b = [];
  if (cur.간지) {
    b.push('지금 지나는 ' + cur.간지 + ' 대운은 앞선 십 년과 성격이 다릅니다. ' +
      이(String(cur.십성 || '').split('/')[0]) + ' 앞에 서면서, 그동안 미뤄 두었던 것이 한꺼번에 몰립니다');
  }
  if (nx.나이 != null) {
    b.push((nx.나이 - 2) + '세 무렵부터 다음 대운의 기운이 먼저 들어옵니다. ' +
      '자리를 옮기거나 사람이 정리되는 시기라, 이때 무엇을 붙잡고 무엇을 놓아야 하는지가 십 년을 가릅니다');
  }
  if (c.용신 && c.기신) {
    b.push('당신에게 순한 기운은 ' + el(c.용신) + ', 버거운 기운은 ' + el(c.기신) +
      '입니다. 앞으로 오는 해 가운데 어느 해가 밀어야 할 해이고 어느 해가 버텨야 할 해인지가 여기서 갈립니다');
  }
  if (se.간지) {
    b.push('올해 ' + (se.년도 || '') + '년만 해도 상반기와 하반기의 결이 뚜렷하게 다릅니다');
  }
  b.push('직업으로는 어떤 자리가 맞고 어떤 자리에서 힘이 빠지는지, ' +
    '관계에서는 어떤 사람과 오래 가는지까지');
  return b.join('. ') + '…';
}

/**
 * buildReading 이 만든 글에 살을 붙인다.
 *
 * @param {object} c     consult (명식표상세 결과의 raw.consult)
 * @param {object} base  cbFortune.buildReading(c)
 * @param {Array}  w     raw.wonguk — 기둥마다의 십성·운성·신살
 */
function enrich(c, base, w) {
  const more = {
    '01': moreSelf, '02': moreBalance, '03': moreYongsin,
    '04': moreTenGod, '05': moreYear,
  };
  const blocks = (base.blocks || []).map((b) => {
    const fn = more[b.no];
    let html = plainHanja(b.html);
    /* 원래 글은 태그 없이 그냥 문장이라, 뒤에 문단을 붙이면 첫 덩어리만
       문단 대접을 못 받아 다음 글과 딱 붙어 보인다. 먼저 문단으로 싸 준다. */
    if (!/^\s*<(p|div|ul|ol|h[1-6])/i.test(html)) html = P(html);
    if (fn) {
      let add = [];
      try { add = fn(c, w) || []; } catch (e) { add = []; }
      if (add.length) html += add.map((t) => P(plainHanja(t))).join('');
    }
    return Object.assign({}, b, { html });
  });
  return Object.assign({}, base, {
    blocks,
    iljuBody: plainHanja(base.iljuBody || ''),
  });
}

module.exports = { enrich, teaserOf, plainHanja };
